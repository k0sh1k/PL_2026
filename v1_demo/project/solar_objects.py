# Кинематическая модель: тело движется по окружности по формуле
#   x = cx + r*cos(angle),  y = cy + r*sin(angle).
# Поэтому тело хранит параметры орбиты, а не массу и скорость.


class Star:
    """Звезда. Неподвижна, служит центром орбит своих планет."""

    type = "star"
    x = 0          # координата x
    y = 0          # координата y
    R = 5          # радиус кружка (пиксели)
    color = "red"  # цвет
    image = None   # id кружка на холсте


class Planet:
    """Планета. Движется по окружности вокруг своей звезды."""

    type = "planet"
    x = 0              # текущая координата x (считается из угла)
    y = 0              # текущая координата y
    R = 5              # радиус кружка
    color = "green"    # цвет
    image = None       # id кружка на холсте

    cx = 0             # центр орбиты x (= координата звезды)
    cy = 0             # центр орбиты y
    orbit_r = 0        # радиус орбиты
    k = 1              # множитель угловой скорости (целое); знак = направление
    angle = 0.0        # текущий угол
    start_angle = 0.0  # стартовый угол (фаза), подобран решателем
    orbit = None       # id нарисованной орбиты
    star_id = 0        # номер звезды (1 или 2)


class Satellite:
    """Спутник планеты. Движется по окружности; структура как у планеты."""

    type = "satellite"
    x = 0
    y = 0
    R = 5
    color = "white"
    image = None

    cx = 0
    cy = 0
    orbit_r = 0
    k = 1
    angle = 0.0
    start_angle = 0.0
    orbit = None
    star_id = 0
