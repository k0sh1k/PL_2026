import math          # математика: cos, sin — для движения по кругу
import tkinter as tk # библиотека окон и рисования (входит в стандартный Python)

WIDTH = 1000
# Ширина окна в пикселях.

HEIGHT = 800
# Высота окна в пикселях.

BASE_STEP = 0.01
# Базовый шаг угла за тик — ТОТ ЖЕ, что в решателе (иначе движение отличалось бы).

CONFIG_FILE = "ticket6_state.txt"
# Имя файла с расстановкой, который мы читаем.


# ============================================================
# КЛАСС ТЕЛА
# ============================================================
class Body:
    # Один объект: звезда, планета или спутник.
    # Звезда стоит на месте; планета и спутник движутся по окружности.

    def __init__(self, kind, R, color, cx, cy, orbit_r, k, phase):
        # Конструктор — вызывается при создании тела, сохраняет все его параметры.
        self.kind = kind        # тип: "star" / "planet" / "satellite"
        self.R = R              # радиус кружка на экране (пиксели)
        self.color = color      # цвет
        self.cx = cx            # центр орбиты по x (для звезды — её положение)
        self.cy = cy            # центр орбиты по y
        self.orbit_r = orbit_r  # радиус орбиты (у звезды 0)
        self.k = k              # множитель скорости (у звезды 0)
        self.angle = phase      # текущий угол (стартует с подобранной фазы)
        self.image = None       # id кружка на холсте (заполнится при рисовании)
        self.orbit_id = None    # id нарисованной орбиты (для кнопки показа/скрытия)

    def position(self):
        # Возвращает текущие координаты тела на экране.
        if self.kind == "star":
            # Звезда не движется — отдаём её центр.
            return self.cx, self.cy
        # Планета/спутник: точка на окружности по текущему углу.
        return (self.cx + self.orbit_r * math.cos(self.angle),
                self.cy + self.orbit_r * math.sin(self.angle))
        # x = центр_x + радиус*cos(угол); y = центр_y + радиус*sin(угол).


# ============================================================
# ЧТЕНИЕ КОНФИГА
# ============================================================
def read_config(filename):
    # Читает тела из текстового файла и возвращает список объектов Body.
    # Форматы строк:
    #   Star      R цвет x y
    #   Planet    R цвет star_id cx cy orbit_r k phase
    #   Satellite R цвет star_id cx cy orbit_r k phase

    bodies = []
    # Список, куда сложим прочитанные тела.

    with open(filename, encoding="utf-8") as f:
        # Открываем файл на чтение (with сам закроет его потом).

        for line in f:
            # Идём по строкам файла по одной.

            line = line.strip()
            # Убираем пробелы и перевод строки по краям.

            if not line or line[0] == "#":
                # Пропускаем пустые строки и комментарии (начинаются с #).
                continue

            p = line.split()
            # Разбиваем строку на части по пробелам. p[0] — тип тела.

            kind = p[0].lower()
            # Тип в нижнем регистре ("star"/"planet"/"satellite").

            if kind == "star":
                # Строка звезды: Star R цвет x y
                bodies.append(Body("star", int(p[1]), p[2], float(p[3]), float(p[4]), 0, 0, 0.0))
                # Создаём звезду: orbit_r=0, k=0, phase=0 (она не движется).
            else:
                # Строка планеты или спутника: тип R цвет star_id cx cy orbit_r k phase
                bodies.append(Body(kind, int(p[1]), p[2], float(p[4]), float(p[5]),
                                   float(p[6]), int(p[7]), float(p[8])))
                # p[3] — star_id, графике он не нужен (движение уже задано), его пропускаем.

    return bodies
    # Возвращаем список всех тел.


# ============================================================
# ПОДГОТОВКА ОКНА И ПЕРВАЯ ОТРИСОВКА
# ============================================================
bodies = read_config(CONFIG_FILE)
# Читаем расстановку из файла.

window = tk.Tk()
# Создаём главное окно.

window.title("Билет №6 - вариант 2 (число пересечений задаётся)")
# Заголовок окна.

canvas = tk.Canvas(window, width=WIDTH, height=HEIGHT, bg="black")
# Создаём холст (чёрный фон) для рисования.

canvas.pack()
# Размещаем холст в окне.

show_orbits = True
# Флаг: показывать ли орбиты (по умолчанию да).

# Рисуем орбиты ОДИН раз (они не двигаются).
for b in bodies:
    # Перебираем все тела.
    if b.kind in ("planet", "satellite"):
        # Орбиты есть только у планет и спутников.
        b.orbit_id = canvas.create_oval(b.cx - b.orbit_r, b.cy - b.orbit_r,
                                        b.cx + b.orbit_r, b.cy + b.orbit_r, outline="gray")
        # Рисуем серую окружность-орбиту и запоминаем её id (для кнопки).

# Рисуем сами тела (кружки) ОДИН раз, потом будем их только двигать.
for b in bodies:
    # Перебираем все тела.
    x, y = b.position()
    # Текущие координаты тела.
    b.image = canvas.create_oval(x - b.R, y - b.R, x + b.R, y + b.R, fill=b.color)
    # Рисуем закрашенный кружок и запоминаем его id (чтобы потом двигать).


# ============================================================
# АНИМАЦИЯ
# ============================================================
def update():
    # Один кадр анимации: двигаем все тела и перерисовываем. Вызывает сама себя по таймеру.

    for b in bodies:
        # Перебираем все тела.

        if b.kind == "star":
            # Звёзды не двигаем.
            continue

        b.angle += b.k * BASE_STEP
        # Увеличиваем угол тела: скорость = k * BASE_STEP. Знак k задаёт направление.

        x, y = b.position()
        # Новые координаты после поворота.

        canvas.coords(b.image, x - b.R, y - b.R, x + b.R, y + b.R)
        # Перемещаем кружок тела в новое место (не создаём заново — просто двигаем).

    window.after(20, update)
    # Просим выполнить update снова через 20 миллисекунд — получается плавная анимация.


# ============================================================
# КНОПКА ВКЛ/ВЫКЛ ОРБИТ
# ============================================================
def toggle_orbits():
    # Включает или выключает показ орбит.

    global show_orbits
    # Говорим, что меняем глобальную переменную show_orbits, а не создаём новую.

    show_orbits = not show_orbits
    # Переключаем флаг: True -> False или False -> True.

    state = "normal" if show_orbits else "hidden"
    # state — "normal" (видно) или "hidden" (спрятано) в зависимости от флага.

    for b in bodies:
        # Перебираем все тела.
        if b.orbit_id is not None:
            # Если у тела есть орбита...
            canvas.itemconfig(b.orbit_id, state=state)
            # ...показываем или прячем её. Орбиту не удаляем — просто меняем видимость.

    button.config(text="Скрыть орбиты" if show_orbits else "Показать орбиты")
    # Меняем надпись на кнопке в зависимости от текущего состояния.


button = tk.Button(window, text="Скрыть орбиты", command=toggle_orbits)
# Создаём кнопку. При нажатии вызывается toggle_orbits.

button.pack()
# Размещаем кнопку в окне (под холстом).


# ============================================================
# ЗАПУСК
# ============================================================
update()
# Запускаем анимацию (первый кадр, дальше она сама повторяется).

window.mainloop()
# Запускаем цикл окна. Программа работает, пока окно не закроют.
