# Отличие от варианта 3: здесь ПОЛЬЗОВАТЕЛЬ сам вводит, сколько пар орбит должны
# пересекаться. Решатель показывает допустимые границы, проверяет ввод, переводит
# число в нужное расстояние между звёздами, подбирает безопасную расстановку и
# записывает её в ticket6_state.txt. Графика (solar_main.py) — та же, что в варианте 3.
