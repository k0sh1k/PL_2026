import math      # математика: cos, sin, pi, sqrt, exp
import random    # случайные числа для отжига


# ============================================================
# ПАРАМЕТРЫ
# ============================================================

BASE_STEP = 0.01
# Базовый шаг угла за тик. Скорости кратны ему => движение периодично.

PERIOD_TICKS = int(round(2 * math.pi / BASE_STEP))
# Длина полного периода в тиках (2*pi / шаг ≈ 628).

PLANET_RADIUS = 4
# Радиус кружка планеты в пикселях.

REQUIRED_GAP = PLANET_RADIUS * 2 + 2
# Безопасный зазор между центрами: диаметр + 2 пикселя запаса = 10.

CENTER_X, CENTER_Y = 500, 400
# Центр экрана.

R1 = [60 + n * 12 for n in range(1, 17)]
# Радиусы 16 орбит первой звезды: 72, 84, ... , 252.

R2 = [60 + n * 10 for n in range(1, 21)]
# Радиусы 20 орбит второй звезды: 70, 80, ... , 260.

MOONS1 = {8, 10, 13}
# Планеты первой звезды со спутниками.

MOONS2 = {10, 15, 20}
# Планеты второй звезды со спутниками.

MAX_WORKABLE_CROSSINGS = 100
# ВЕРХНЯЯ граница выбора. До 100 пересечений планеты нормального размера (радиус 4)
# ещё свободно расходятся. Выше система слишком тесная — пришлось бы делать планеты
# точками и долго считать. Поэтому больше 100 не разрешаем. (Проверено экспериментально.)

MIN_CROSSINGS = 1
# НИЖНЯЯ граница: хотя бы одна пара орбит должна пересекаться (иначе условие билета
# "орбиты звёзд пересекаются" не выполнено вообще).

TOTAL_PAIRS = len(R1) * len(R2)
# Всего возможных пар орбит: 16 * 20 = 320. Нужно для показа процента.


# ============================================================
# СКОЛЬКО ПАР ОРБИТ ПЕРЕСЕКАЕТСЯ ПРИ РАССТОЯНИИ D
# ============================================================
def cross_count(D):
    # Считает, сколько пар орбит пересекается, если звёзды на расстоянии D.
    # Две окружности (радиусы a и b, центры на расстоянии D) пересекаются,
    # когда |a - b| < D < a + b.
    return sum(1 for a in R1 for b in R2 if abs(a - b) < D < a + b)
    # Перебираем все пары (a из R1, b из R2), считаем, для скольких условие верно.


# ============================================================
# ПЕРЕВОД: СКОЛЬКО ПЕРЕСЕЧЕНИЙ ХОЧЕТ ПОЛЬЗОВАТЕЛЬ -> КАКОЕ РАССТОЯНИЕ D
# ============================================================
def find_distance_for(target):
    # По желаемому числу пересечений target подбирает расстояние D между звёздами.
    # Чем БЛИЖЕ звёзды, тем БОЛЬШЕ орбит пересекается. Перебираем расстояния и берём то,
    # которое даёт число пересечений, ближайшее к target.

    best_D = None
    # best_D — лучшее найденное расстояние (пока нет).

    best_diff = 10 ** 9
    # best_diff — насколько лучшее D промахивается мимо target (пока очень много).

    best_c = 0
    # best_c — сколько пересечений даёт лучшее D.

    for D in range(150, 512, 2):
        # Перебираем расстояния от 150 до 510 пикселей с шагом 2.
        # D >= 150, чтобы звёзды не оказались слишком близко (иначе всё сольётся).

        c = cross_count(D)
        # Сколько пересечений при этом D.

        diff = abs(c - target)
        # Насколько это отличается от желаемого числа.

        if diff < best_diff:
            # Если этот D ближе к цели, чем все предыдущие...
            best_diff = diff
            # ...запоминаем новую минимальную разницу...
            best_D = D
            # ...само расстояние...
            best_c = c
            # ...и число пересечений при нём.

    return best_D, best_c
    # Возвращаем лучшее расстояние и реально достижимое при нём число пересечений.


# ============================================================
# СОЗДАНИЕ ПЛАНЕТ И СПУТНИКОВ (как в варианте 3)
# ============================================================
def make_bodies(D):
    # Создаёт тела обеих звёзд при заданном расстоянии D между звёздами.
    # Знак скорости k задаётся по чётности орбиты (направление вращения).

    s1x = CENTER_X - D / 2
    # x первой звезды — левее центра на пол-расстояния.

    s2x = CENTER_X + D / 2
    # x второй звезды — правее центра на пол-расстояния.

    b1 = []
    # Тела первой звезды.

    b2 = []
    # Тела второй звезды.

    for idx, n in enumerate(range(1, 17)):
        # Орбиты 1..16 первой звезды (idx — позиция, n — номер орбиты).

        r = R1[idx]
        # Радиус орбиты.

        sign = 1 if n % 2 == 0 else -1
        # Чётная орбита +1 (по часовой), нечётная -1 (против).

        b1.append({
            "cx": s1x, "cy": CENTER_Y, "r": r,
            "k": sign * (16 - n + 1),   # стартовая скорость со знаком по чётности
            "phase": 0.0,
            "color": "deepskyblue", "star_id": 1, "is_moon": False
        })
        # Добавили планету (словарь с её параметрами).

        if n in MOONS1:
            # Если нужен спутник...
            b1.append({
                "cx": s1x, "cy": CENTER_Y, "r": r + 7,
                "k": sign * (16 - n + 1),
                "phase": 0.0,
                "color": "white", "star_id": 1, "is_moon": True
            })
            # ...добавили спутник рядом с планетой.

    for idx, n in enumerate(range(1, 21)):
        # Орбиты 1..20 второй звезды.

        r = R2[idx]
        # Радиус.

        sign = 1 if n % 2 == 0 else -1
        # Направление по чётности.

        b2.append({
            "cx": s2x, "cy": CENTER_Y, "r": r,
            "k": sign * (20 - n + 1),
            "phase": 0.0,
            "color": "orangered", "star_id": 2, "is_moon": False
        })
        # Планета второй звезды.

        if n in MOONS2:
            # Спутник для нужных планет.
            b2.append({
                "cx": s2x, "cy": CENTER_Y, "r": r + 7,
                "k": sign * (20 - n + 1),
                "phase": 0.0,
                "color": "white", "star_id": 2, "is_moon": True
            })

    return b1, b2, s1x, s2x
    # Возвращаем тела и координаты звёзд.


# ============================================================
# МИНИМАЛЬНЫЙ ЗАЗОР ЗА ПЕРИОД (как в варианте 3)
# ============================================================
def min_gap(b1, b2, step=1):
    # Минимальное расстояние между телами РАЗНЫХ звёзд за весь период.
    # step — через сколько тиков проверять (1 — точно, больше — быстрее).

    md = 1e30
    # Начальный минимум — очень большое число.

    for t in range(0, PERIOD_TICKS, step):
        # Идём по моментам времени.

        p1 = [(b["cx"] + b["r"] * math.cos(b["phase"] + b["k"] * BASE_STEP * t),
               b["cy"] + b["r"] * math.sin(b["phase"] + b["k"] * BASE_STEP * t)) for b in b1]
        # Координаты всех тел первой звезды в момент t (по формуле движения по кругу).

        p2 = [(b["cx"] + b["r"] * math.cos(b["phase"] + b["k"] * BASE_STEP * t),
               b["cy"] + b["r"] * math.sin(b["phase"] + b["k"] * BASE_STEP * t)) for b in b2]
        # Координаты всех тел второй звезды.

        for x1, y1 in p1:
            # Каждое тело первой звезды...

            for x2, y2 in p2:
                # ...против каждого тела второй.

                d = (x1 - x2) ** 2 + (y1 - y2) ** 2
                # Квадрат расстояния (без корня — быстрее).

                if d < md:
                    # Если ближе текущего минимума...
                    md = d
                    # ...обновляем минимум.

    return math.sqrt(md)
    # Возвращаем настоящее минимальное расстояние (корень из минимального квадрата).


# ============================================================
# ПОДБОР: имитация отжига (как в варианте 3)
# ============================================================
def solve(b1, b2, seed=5):
    # Подбирает фазы и величины скоростей, максимизируя минимальный зазор.

    random.seed(seed)
    # Фиксируем случайность для повторяемости.

    for b in b1 + b2:
        # Стартовая перемешка всех тел.
        b["phase"] = random.uniform(0, 2 * math.pi)
        # Случайный стартовый угол.
        sign = 1 if b["k"] > 0 else -1
        # Сохраняем знак (направление вращения по чётности).
        b["k"] = sign * random.randint(1, 18)
        # Случайная величина скорости с тем же знаком.

    def new_k(old):
        # Новая скорость с тем же знаком, что у старой.
        sign = 1 if old > 0 else -1
        return sign * random.randint(1, 18)

    def anneal(step, iterations, T0):
        # Один проход отжига.
        cur = min_gap(b1, b2, step)
        # Текущий зазор.
        best = cur
        # Лучший зазор.
        best_state = [(b["phase"], b["k"]) for b in b1 + b2]
        # Копия лучшей расстановки.
        T = T0
        # Стартовая температура.

        for _ in range(iterations):
            # Повторяем нужное число проб.

            b = random.choice(b1 + b2)
            # Случайное тело для изменения.

            if random.random() < 0.6:
                # 60%: меняем угол.
                fld = "phase"; old = b["phase"]; b["phase"] = random.uniform(0, 2 * math.pi)
            else:
                # 40%: меняем величину скорости.
                fld = "k"; old = b["k"]; b["k"] = new_k(old)

            cand = min_gap(b1, b2, step)
            # Зазор после изменения.

            if cand >= cur or random.random() < math.exp((cand - cur) / max(T, 1e-3)) * 0.1:
                # Принимаем, если не хуже или (иногда) даже если хуже — чтобы не застрять.
                cur = cand
                if cur > best:
                    best = cur
                    best_state = [(bb["phase"], bb["k"]) for bb in b1 + b2]
            else:
                # Иначе откатываем изменение.
                b[fld] = old

            T *= 0.9995
            # Остужаем температуру.

            if best > REQUIRED_GAP * 1.4:
                # Достигли зазора с запасом — выходим раньше.
                break

        for bb, (ph, k) in zip(b1 + b2, best_state):
            # Возвращаемся к лучшей расстановке.
            bb["phase"] = ph
            bb["k"] = k

        return best

    anneal(step=3, iterations=2000, T0=1.0)
    # Грубый проход (быстро, через 3 тика).

    return anneal(step=1, iterations=2500, T0=0.5)
    # Точный проход (каждый тик) — финал обязательно точный.


# ============================================================
# ЗАПИСЬ КОНФИГА (как в варианте 3, плюс число пересечений в шапку)
# ============================================================
def save_config(filename, b1, b2, s1x, s2x, crossings):
    # Записывает расстановку в файл. crossings — выбранное число пересечений (для шапки).

    def line(b):
        # Превращает тело в строку.
        name = "Satellite" if b["is_moon"] else "Planet"
        R = 2 if b["is_moon"] else PLANET_RADIUS
        return "%s %d %s %d %.1f %.1f %.1f %d %.6f" % (
            name, R, b["color"], b["star_id"], b["cx"], b["cy"], b["r"], b["k"], b["phase"])

    lines = ["# Билет №6 — ВАРИАНТ 2 (выбрано пересечений пар орбит: %d)" % crossings,
             "# Star R цвет x y | Planet/Satellite R цвет star_id cx cy orbit_r k phase",
             "", "# ЗВЕЗДА 1", "Star 14 yellow %.1f %.1f" % (s1x, CENTER_Y)]
    # Шапка с выбранным числом пересечений и заголовок первой звезды.

    lines += [line(b) for b in b1]
    # Строки тел первой звезды.

    lines += ["", "# ЗВЕЗДА 2", "Star 14 orange %.1f %.1f" % (s2x, CENTER_Y)]
    # Заголовок второй звезды.

    lines += [line(b) for b in b2]
    # Строки тел второй звезды.

    with open(filename, "w", encoding="utf-8") as f:
        # Открываем файл на запись.
        f.write("\n".join(lines) + "\n")
        # Пишем все строки.


# ============================================================
# ВВОД ЧИСЛА ПЕРЕСЕЧЕНИЙ ОТ ПОЛЬЗОВАТЕЛЯ (главное отличие варианта 2)
# ============================================================
def ask_crossings():
    # Спрашивает у пользователя число пересечений и проверяет корректность ввода.
    # Возвращает корректное число в диапазоне [MIN_CROSSINGS, MAX_WORKABLE_CROSSINGS].

    print("=== ВАРИАНТ 2: выбор числа пересечений орбит ===")
    # Заголовок.

    print("Всего возможных пар орбит (16 x 20): %d" % TOTAL_PAIRS)
    # Сообщаем общее число пар (320).

    print("Можно выбрать, сколько пар орбит двух звёзд будут пересекаться.")
    # Поясняем смысл выбора.

    print("Допустимый диапазон: от %d до %d пар" % (MIN_CROSSINGS, MAX_WORKABLE_CROSSINGS))
    # Показываем границы выбора.

    print("(выше %d система становится слишком тесной для планет нормального размера)"
          % MAX_WORKABLE_CROSSINGS)
    # Честно объясняем, почему есть верхний предел.

    while True:
        # Бесконечный цикл: повторяем запрос, пока пользователь не введёт корректное число.

        try:
            # Пробуем прочитать и преобразовать ввод (может быть ошибка, если введут не число).

            raw = input("Введите число пересечений [%d..%d]: "
                        % (MIN_CROSSINGS, MAX_WORKABLE_CROSSINGS))
            # Читаем строку с клавиатуры.

            value = int(raw)
            # Пытаемся превратить её в целое число.

        except (ValueError, EOFError):
            # Если введено не число (ValueError) или ввод закончился (EOFError)...
            print("Нужно целое число. Попробуйте снова.")
            # ...сообщаем об ошибке...
            continue
            # ...и повторяем запрос с начала цикла.

        if value < MIN_CROSSINGS:
            # Если число меньше минимума...
            print("Слишком мало. Минимум %d." % MIN_CROSSINGS)
            # ...сообщаем и просим снова (цикл продолжится).

        elif value > MAX_WORKABLE_CROSSINGS:
            # Если число больше максимума...
            print("Слишком много. Максимум %d (иначе планеты не помещаются)."
                  % MAX_WORKABLE_CROSSINGS)
            # ...сообщаем и просим снова.

        else:
            # Если число в допустимых границах...
            return value
            # ...возвращаем его и выходим из функции.


# ============================================================
# ГЛАВНАЯ ФУНКЦИЯ
# ============================================================
def main():
    # Связывает все шаги вместе.

    target = ask_crossings()
    # Спрашиваем у пользователя желаемое число пересечений.

    D, real_c = find_distance_for(target)
    # Подбираем расстояние D под это число; real_c — реально достижимое число пересечений.

    print()
    # Пустая строка для красоты вывода.

    print("Выбрано пересечений: %d (фактически достижимо: %d, это %d%%)"
          % (target, real_c, 100 * real_c // TOTAL_PAIRS))
    # Показываем, что выбрано и что реально получилось (число и процент).

    print("Расстояние между звёздами: %d px" % D)
    # Показываем найденное расстояние.

    b1, b2, s1x, s2x = make_bodies(D)
    # Создаём тела при этом расстоянии.

    print("Подбор безопасной конфигурации (отжиг)...")
    # Сообщаем о начале подбора.

    solve(b1, b2)
    # Подбираем безопасную расстановку.

    final = min_gap(b1, b2, step=1)
    # Считаем итоговый зазор точно.

    print("Минимальный зазор за период: %.2f px (нужно > %d)" % (final, PLANET_RADIUS * 2))
    # Печатаем зазор и порог (диаметр).

    print("РЕЗУЛЬТАТ:", "безопасно — планеты не сталкиваются" if final > PLANET_RADIUS * 2
          else "ВНИМАНИЕ: зазор мал, выберите меньше пересечений")
    # Вывод результата.

    save_config("ticket6_state.txt", b1, b2, s1x, s2x, real_c)
    # Записываем конфиг (с числом пересечений в шапке).

    print("Конфигурация записана в ticket6_state.txt")
    # Сообщаем о готовности файла.

    print("Теперь запустите:  python solar_main.py")
    # Подсказываем следующий шаг.


if __name__ == "__main__":
    # Если файл запущен напрямую — выполнить main().
    main()
